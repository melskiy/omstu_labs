-- ============================================================================
-- ЗАПРОС 1: Поиск авторов со строгим форматом записи инициалов
-- ============================================================================
-- Цель: Отобрать всех авторов, у которых ФИО записано строго в формате:
--       "Фамилия И.О." (Фамилия с заглавной буквы, строчные буквы, пробел, 
--       две заглавные буквы с точками: например, "Пушкин А.С.").

-- Вариант 1 (PostgreSQL POSIX оператор ~):
SELECT 
    Code_author, 
    name_author, 
    Birthday
FROM Authors
WHERE name_author ~ '^[А-ЯЁ][а-яё]+ [А-ЯЁ]\.[А-ЯЁ]\.$';

-- ============================================================================
-- ЗАПРОС 2: Поиск издательств и городов с составными названиями через дефис
-- ============================================================================
-- Цель: Найти издательства или города, в которых название содержит дефис 
--       между словами (например, "Питер-Пресс", "ДМК-Пресс", "Санкт-Петербург", 
--       "Ростов-на-Дону"). 
--       Аналог примера из лекции: WHERE position REGEXP '^[а-яА-Я]+-[а-яА-Я]+$'
--
-- Разбор регулярного выражения: ^[а-яА-ЯёЁ]+-[а-яА-ЯёЁ]+
--   ^            - строка начинается со слова;
--   [а-яА-ЯёЁ]+  - одно или более русских букв;
--   -            - обязательный символ дефиса;
--   [а-яА-ЯёЁ]+  - одно или более русских букв после дефиса.

-- Вариант 1 (PostgreSQL POSIX оператор ~):
SELECT 
    Code_publish, 
    Publish, 
    City
FROM Publishing_house
WHERE Publish ~ '^[а-яА-ЯёЁ]+-[а-яА-ЯёЁ]+'
   OR City ~ '^[а-яА-ЯёЁ]+-[а-яА-ЯёЁ]+';


-- ============================================================================
-- ЗАПРОС 3: Поиск книг, содержащих в названии латинские термины или слова
-- ============================================================================
-- Цель: Вывести книги, авторов и издательства для книг, в названии которых 
--       встречаются английские термины/слова (книги по IT, языкам программирования,
--       например: "Python", "PostgreSQL", "Clean Code", "Java").
--       Аналог примера из лекции: WHERE position REGEXP '[a-zA-Z]+\\b'
--
-- Разбор регулярного выражения: [a-zA-Z]+
--   [a-zA-Z] - любая английская буква (верхний или нижний регистр);
--   +        - один или более символов подряд.
-- В PostgreSQL оператор ~* выполняет регистронезависимое сравнение.

-- Вариант 1 (PostgreSQL POSIX оператор ~* с JOIN):
SELECT 
    b.Code_book, 
    b.Title_book, 
    a.name_author, 
    p.Publish, 
    b.Pages
FROM Books b
JOIN Authors a ON b.Code_author = a.Code_author
LEFT JOIN Publishing_house p ON b.Code_publish = p.Code_publish
WHERE b.Title_book ~* '[a-z]+';

-- ============================================================================
-- ЗАПРОС 4: Поиск книг с короткими русскими словами длиной не более 2 символов
-- ============================================================================
-- Цель: Найти названия книг, содержащие отдельные короткие русские слова 
--       длиной 1-2 символа (предлоги и союзы: "и", "в", "о", "на", "по" и др.),
--       например: "Война и мир", "Сказка о царе Салтане", "Clean Code на Java".
--       В точности воспроизводит алгоритм с 4 позициями слова из слайда лекции:
--       "Регулярное выражение: ?" (Преподаватель: доц. Озерова Г.П.).
--
-- Разбор регулярного выражения:
--   ^[а-яА-ЯёЁ][а-яА-ЯёЁ]?$  - одно короткое слово во всем названии;
--   ^[а-яА-ЯёЁ][а-яА-ЯёЁ]?   - короткое слово в начале строки перед пробелом;
--    [а-яА-ЯёЁ][а-яА-ЯёЁ]?$  - короткое слово после пробела в конце строки;
--    [а-яА-ЯёЁ][а-яА-ЯёЁ]?   - короткое слово в середине строки, окруженное пробелами.
--   Символ ? означает, что вторая буква может отсутствовать (длина 1 или 2 символа).

-- Вариант 1 (PostgreSQL POSIX оператор ~):
SELECT 
    Code_book, 
    Title_book, 
    Pages
FROM Books
WHERE Title_book ~ '^[а-яА-ЯёЁ][а-яА-ЯёЁ]?$|^[а-яА-ЯёЁ][а-яА-ЯёЁ]? | [а-яА-ЯёЁ][а-яА-ЯёЁ]?$| [а-яА-ЯёЁ][а-яА-ЯёЁ]? ';


-- ============================================================================
-- ЗАПРОС 5: Валидация формата ИНН компаний-доставщиков (10 или 12 цифр)
-- ============================================================================
-- Цель: Проверить корректность заполнения реквизита ИНН в таблице Deliveries.
--       По законодательству РФ:
--         - ИНН юридического лица состоит ровно из 10 цифр;
--         - ИНН индивидуального предпринимателя (ИП) состоит ровно из 12 цифр.
--       Строка не должна содержать посторонних букв, знаков или иметь иную длину.
--       Демонстрирует квантификаторы фиксированной длины, диапазоны [0-9],
--       оператор альтернативы | и оператор отрицания !~ (NOT REGEXP).

-- Вариант 5.1: Выборка всех компаний с КОРРЕКТНЫМ форматом ИНН
SELECT 
    Code_delivery, 
    Name_delivery, 
    Name_company, 
    INN, 
    Phone
FROM Deliveries
WHERE INN ~ '^[0-9]{10}$|^[0-9]{12}$';

-- Вариант 5.2: Выборка записей с ОШИБОЧНЫМ форматом ИНН (контроль качества данных)
-- Использование оператора отрицания !~ (аналог NOT REGEXP из лекции)
SELECT 
    Code_delivery, 
    Name_delivery, 
    Name_company, 
    INN,
    'Неверный формат ИНН' AS Error_Description
FROM Deliveries
WHERE INN !~ '^[0-9]{10}$|^[0-9]{12}$';
