CREATE TABLE Authors (
    Code_author INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_author VARCHAR(30),
    Birthday DATE
);

CREATE TABLE Publishing_house (
    Code_publish INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Publish VARCHAR(30),
    City VARCHAR(20)
);

CREATE TABLE Books (
    Code_book INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Title_book VARCHAR(40),
    Code_author INT REFERENCES Authors(Code_author) ON DELETE CASCADE,
    Pages INT,
    Code_publish INT REFERENCES Publishing_house(Code_publish) ON DELETE SET NULL
);

CREATE TABLE Deliveries (
    Code_delivery INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name_delivery VARCHAR(30),
    Name_company VARCHAR(20),
    Address VARCHAR(100),
    Phone BIGINT,
    INN VARCHAR(13)
);

CREATE TABLE Purchases (
    Code_purchase INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Code_book INT REFERENCES Books(Code_book) ON DELETE CASCADE,
    Date_order TIMESTAMP(0),
    Code_delivery INT REFERENCES Deliveries(Code_delivery) ON DELETE SET NULL,
    Type_purchase BOOLEAN,
    Cost NUMERIC(10, 2),
    Amount INT
);