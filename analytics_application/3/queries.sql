-- ============================================================================
-- ПРИМЕР 1: Обход иерархических структур данных (Дерево рубрик и жанров книг)
-- ============================================================================
-- Назначение (из лекции, слайды 21–30):
--   Обработка данных, представленных в иерархическом виде (родитель -> потомок).
-- Задача:
--   Построить полное дерево категорий книг, вычислить уровень вложенности
--   (level) каждой рубрики и сформировать понятный путь классификации (хлебные крошки).
--   Найти все подкатегории раздела "Компьютерная литература" (id = 3).

WITH RECURSIVE CategoryHierarchy AS (
    -- Анкерная часть: начинаем с выбранного узла (например, раздела 'Компьютерная литература')
    SELECT 
        Code_category,
        Category_name,
        Parent_category_id,
        0 AS level,
        Category_name::TEXT AS full_path
    FROM Book_categories
    WHERE Code_category = 3
    
    UNION ALL
    
    -- Рекурсивная часть: присоединяем дочерние категории
    SELECT 
        child.Code_category,
        child.Category_name,
        child.Parent_category_id,
        parent.level + 1 AS level,
        parent.full_path || ' -> ' || child.Category_name AS full_path
    FROM Book_categories child
    INNER JOIN CategoryHierarchy parent 
        ON child.Parent_category_id = parent.Code_category
)
SELECT 
    Code_category,
    Category_name,
    Parent_category_id,
    level,
    full_path
FROM CategoryHierarchy
ORDER BY level, Code_category;


-- ============================================================================
-- ПРИМЕР 2: Поиск путей в графе (Логистическая сеть маршрутов доставки)
-- ============================================================================
-- Назначение (из лекции, слайды 31–48):
--   Обработка данных, представленных в виде графа (поиск достижимых вершин и путей).
-- Задача:
--   Определить, в какие города возможна доставка книг из центрального склада
--   в Москве (напрямую и с перегрузкой/транзитом), рассчитать суммарное расстояние
--   (Distance_km), количество перегрузочных пунктов (hops) и восстановить полный маршрут.

WITH RECURSIVE DeliveryPaths AS (
    -- Анкерная часть: прямые рейсы из начального пункта 'Москва'
    SELECT 
        City_from,
        City_to,
        Distance_km,
        1 AS hops,
        City_from || ' -> ' || City_to AS full_route
    FROM Delivery_routes
    WHERE City_from = 'Москва'
    
    UNION ALL
    
    -- Рекурсивная часть: находим транзитные рейсы из промежуточных городов
    SELECT 
        dp.City_from,
        r.City_to,
        dp.Distance_km + r.Distance_km AS Distance_km,
        dp.hops + 1 AS hops,
        dp.full_route || ' -> ' || r.City_to AS full_route
    FROM Delivery_routes r
    INNER JOIN DeliveryPaths dp 
        ON r.City_from = dp.City_to
    WHERE dp.hops < 5 -- Защита от бесконечного цикла в циклическом графе
)
SELECT 
    City_from AS Origin_City,
    City_to AS Destination_City,
    Distance_km AS Total_Distance_km,
    hops AS Transit_Count,
    full_route
FROM DeliveryPaths
ORDER BY Distance_km;


-- ============================================================================
-- ПРИМЕР 3: Генерация последовательностей дат и анализ непрерывной выручки
-- ============================================================================
-- Назначение (из лекции, слайды 11–20 и 49–60):
--   Генерация непрерывного числового/временного ряда и объединение с реальными данными.
-- Задача:
--   В таблице Purchases заказы оформляются не каждый день. С помощью рекурсивного CTE
--   сгенерировать непрерывный календарный ряд дней за первую половину марта 2024 года,
--   объединить с таблицей покупок через LEFT JOIN и рассчитать ежедневную выручку,
--   отображая 0 для дней, в которые покупок не было.

WITH RECURSIVE CalendarDates AS (
    -- Анкерная часть: начальная дата периода
    SELECT '2024-03-01'::DATE AS calendar_date
    
    UNION ALL
    
    -- Рекурсивная часть: инкремент даты на 1 день вперед
    SELECT (calendar_date + INTERVAL '1 day')::DATE
    FROM CalendarDates
    WHERE calendar_date < '2024-03-12'::DATE -- Конечное условие генерации
)
SELECT 
    c.calendar_date,
    COUNT(p.Code_purchase) AS orders_count,
    COALESCE(SUM(p.Cost * p.Amount), 0.00) AS daily_revenue
FROM CalendarDates c
LEFT JOIN Purchases p 
    ON c.calendar_date = p.Date_order::DATE
GROUP BY c.calendar_date
ORDER BY c.calendar_date;
